package org.de.rikr.theme;

import java.awt.*;

/**
 * Immutable bundle of colors for a theme. New themes provide a palette instance
 * and the SettingsManager applies it to the global Theme fields at runtime.
 */
public final class ThemePalette {
    // Core surfaces
    public final Color BACKGROUND_COLOR;
    public final Color CONTENT_BACKGROUND_COLOR;

    // Accents & content
    public final Color NAVBAR_BUTTON_SELECTED_COLOR;
    public final Color SEARCH_BUTTON_SELECTED_COLOR;
    public final Color CONTENT_SELECTED_HIGHLIGHT_COLOR;
    public final Color SEARCH_HIGHLIGHT_COLOR;
    public final Color CONTENT_TEXT_COLOR;
    public final Color CONTENT_BORDER_COLOR;
    public final Color CONTENT_HIGHLIGHT_TEXT_COLOR;

    // Syntax
    public final Color SYNTAX_HIGHLIGHT_DEFAULT_COLOR;
    public final Color SYNTAX_HIGHLIGHT_KEYWORD_COLOR;
    public final Color SYNTAX_HIGHLIGHT_COMMENT_COLOR;
    public final Color SYNTAX_HIGHLIGHT_NUMBER_COLOR;
    public final Color SYNTAX_HIGHLIGHT_STRING_COLOR;
    public final Color SYNTAX_HIGHLIGHT_ANNOTATION_COLOR;

    public ThemePalette(
        Color BACKGROUND_COLOR,
        Color CONTENT_BACKGROUND_COLOR,
        Color NAVBAR_BUTTON_SELECTED_COLOR,
        Color SEARCH_BUTTON_SELECTED_COLOR,
        Color CONTENT_SELECTED_HIGHLIGHT_COLOR,
        Color SEARCH_HIGHLIGHT_COLOR,
        Color CONTENT_TEXT_COLOR,
        Color CONTENT_BORDER_COLOR,
        Color CONTENT_HIGHLIGHT_TEXT_COLOR,
        Color SYNTAX_HIGHLIGHT_DEFAULT_COLOR,
        Color SYNTAX_HIGHLIGHT_KEYWORD_COLOR,
        Color SYNTAX_HIGHLIGHT_COMMENT_COLOR,
        Color SYNTAX_HIGHLIGHT_NUMBER_COLOR,
        Color SYNTAX_HIGHLIGHT_STRING_COLOR,
        Color SYNTAX_HIGHLIGHT_ANNOTATION_COLOR
    ) {
        this.BACKGROUND_COLOR = BACKGROUND_COLOR;
        this.CONTENT_BACKGROUND_COLOR = CONTENT_BACKGROUND_COLOR;
        this.NAVBAR_BUTTON_SELECTED_COLOR = NAVBAR_BUTTON_SELECTED_COLOR;
        this.SEARCH_BUTTON_SELECTED_COLOR = SEARCH_BUTTON_SELECTED_COLOR;
        this.CONTENT_SELECTED_HIGHLIGHT_COLOR = CONTENT_SELECTED_HIGHLIGHT_COLOR;
        this.SEARCH_HIGHLIGHT_COLOR = SEARCH_HIGHLIGHT_COLOR;
        this.CONTENT_TEXT_COLOR = CONTENT_TEXT_COLOR;
        this.CONTENT_BORDER_COLOR = CONTENT_BORDER_COLOR;
        this.CONTENT_HIGHLIGHT_TEXT_COLOR = CONTENT_HIGHLIGHT_TEXT_COLOR;
        this.SYNTAX_HIGHLIGHT_DEFAULT_COLOR = SYNTAX_HIGHLIGHT_DEFAULT_COLOR;
        this.SYNTAX_HIGHLIGHT_KEYWORD_COLOR = SYNTAX_HIGHLIGHT_KEYWORD_COLOR;
        this.SYNTAX_HIGHLIGHT_COMMENT_COLOR = SYNTAX_HIGHLIGHT_COMMENT_COLOR;
        this.SYNTAX_HIGHLIGHT_NUMBER_COLOR = SYNTAX_HIGHLIGHT_NUMBER_COLOR;
        this.SYNTAX_HIGHLIGHT_STRING_COLOR = SYNTAX_HIGHLIGHT_STRING_COLOR;
        this.SYNTAX_HIGHLIGHT_ANNOTATION_COLOR = SYNTAX_HIGHLIGHT_ANNOTATION_COLOR;
    }
}
